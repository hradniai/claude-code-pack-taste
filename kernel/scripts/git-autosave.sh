#!/bin/bash
# git-autosave.sh - local-only git safety net (NO GitHub, NO push).
# A "time machine" for work folders so nothing is ever lost - the user never has
# to run a git command. Git identity is taken from the user's own global git
# config; this script never sets a name or email.
#
# Modes:
#   ensure  - SessionStart / setup: if CWD isn't a git repo, `git init` + write a
#             safe .gitignore. If it IS a repo but has no .gitignore, write one
#             (so the first commit can't leak secrets).
#   commit  - checkpoint: stage everything + commit LOCALLY. Only if there are changes.
#
# Hard guarantees:
#   - NEVER pushes anywhere. Local commits only.
#   - Only ever operates inside the workspace root (never random dirs):
#     $PACK_WORKSPACE_ROOT, which the install writes into the env block of
#     ~/.claude/settings.json, else ~/Documents/.
#   - Never overwrites an existing .gitignore.
#   - Skips headless (claude -p) sessions.
set -uo pipefail

MODE="${1:-}"
CWD="$(pwd)"

# Skip headless (claude -p / --print) subprocess sessions. Walk up the process
# tree to the nearest claude process and read only ITS flags, so a " -p " on some
# other ancestor's command line (a calling shell running `mkdir -p ...`) does not
# count. `ps -o args= -p` and `ps -o ppid= -p` work with BSD ps (macOS) and procps.
is_headless_claude() {
  local pid="$PPID" args prog i n
  local -a argv
  for n in 1 2 3 4 5 6 7 8; do
    case "$pid" in ''|*[!0-9]*|0|1) return 1 ;; esac
    args=$(ps -o args= -p "$pid" 2>/dev/null) || return 1
    case "$args" in *[![:space:]]*) ;; *) return 1 ;; esac
    read -r -a argv <<< "$args"
    prog="${argv[0]##*/}"
    i=1
    if [ "$prog" != claude ]; then
      # npm installs show up as `node /path/to/claude ...`
      case "$prog" in
        node|nodejs|bun)
          if [ "${#argv[@]}" -gt 1 ] && [ "${argv[1]##*/}" = claude ]; then i=2; else prog=""; fi ;;
        *) prog="" ;;
      esac
    fi
    if [ -n "$prog" ]; then
      while [ "$i" -lt "${#argv[@]}" ]; do
        case "${argv[$i]}" in -p|--print) return 0 ;; esac
        i=$((i + 1))
      done
      return 1
    fi
    pid=$(ps -o ppid= -p "$pid" 2>/dev/null | tr -d ' ')
  done
  return 1
}
is_headless_claude && exit 0

# Only operate inside the user's workspace root. Set PACK_WORKSPACE_ROOT in the
# env block of ~/.claude/settings.json if your projects live outside ~/Documents.
WORK_ROOT="${PACK_WORKSPACE_ROOT:-$HOME/Documents}"
WORK_ROOT="${WORK_ROOT/#\~/$HOME}"   # settings.json does not expand a leading ~
WORK_ROOT="${WORK_ROOT%/}"
# An empty root or "/" would turn the guard below into "any absolute path".
[ -n "$WORK_ROOT" ] || exit 0
case "$CWD" in
  "$WORK_ROOT"/*) : ;;
  *) exit 0 ;;
esac

write_gitignore_if_missing() {
  [[ -f "$CWD/.gitignore" ]] && return 0
  # Prefer the universal standard template (single source of truth). Fall back to
  # the inline minimal secrets-first version if the template is missing.
  local tpl="$HOME/.claude/templates/gitignore"
  if [[ -f "$tpl" ]]; then
    cp "$tpl" "$CWD/.gitignore"
    return 0
  fi
  cat > "$CWD/.gitignore" <<'EOF'
# Auto-generated by git-autosave (local safety net). Edit freely.
# --- Secrets - never version these ---
.env
.env.*
*.env
**/.env
**/.env.*
!.env.example
!.env.template
!**/.env.example
!**/.env.template
*.key
*.pem
*.p12
*.pfx
*-credentials.json
credentials.json
.credentials.json
**/secrets/*.env
*.dec.yaml
# --- Dependencies / build output ---
**/node_modules/
**/.next/
**/dist/
**/build/
**/.venv/
**/__pycache__/
# --- OS / editor noise ---
.DS_Store
Thumbs.db
*.swp
*.swo
EOF
}

is_git() { git -C "$CWD" rev-parse --is-inside-work-tree >/dev/null 2>&1; }

case "$MODE" in
  ensure)
    if ! is_git; then
      git -C "$CWD" init -q || exit 0
      # Git identity is intentionally NOT set here - it uses the user's own
      # global ~/.gitconfig (user.name / user.email).
    fi
    write_gitignore_if_missing
    ;;
  commit)
    is_git || exit 0
    git -C "$CWD" add -A 2>/dev/null || exit 0
    # Nothing staged -> nothing to do.
    git -C "$CWD" diff --cached --quiet 2>/dev/null && exit 0
    TS=$(date "+%Y-%m-%d %H:%M")
    git -C "$CWD" commit -q -m "checkpoint: auto-save $TS" 2>/dev/null || true
    ;;
  *)
    echo "usage: git-autosave.sh {ensure|commit}" >&2
    exit 1
    ;;
esac
exit 0
